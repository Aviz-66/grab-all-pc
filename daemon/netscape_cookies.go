package main

import (
	"fmt"
	"os"
	"strings"
	"time"
)

// Cookie represents a browser cookie received from the Chrome/Brave extension.
type Cookie struct {
	Name           string  `json:"name"`
	Value          string  `json:"value"`
	Domain         string  `json:"domain"`
	Path           string  `json:"path"`
	Secure         bool    `json:"secure"`
	HostOnly       bool    `json:"hostOnly,omitempty"`
	Session        bool    `json:"session,omitempty"`
	ExpirationDate float64 `json:"expirationDate,omitempty"`
}

// WriteNetscapeCookiesFile writes cookies in the standard Netscape/curl cookies.txt format.
// This format is required by yt-dlp (--cookies flag).
func WriteNetscapeCookiesFile(cookies []Cookie, filePath string) error {
	var builder strings.Builder
	builder.WriteString("# Netscape HTTP Cookie File\n")
	builder.WriteString("# https://curl.se/docs/http-cookies.html\n")
	builder.WriteString("# This file was generated by GrabAll Download Manager.\n\n")

	nowUnix := time.Now().Unix()
	for _, c := range cookies {
		name := strings.TrimSpace(c.Name)
		if name == "" || strings.ContainsAny(name, "\r\n\t") || strings.ContainsAny(c.Value, "\r\n\t") {
			continue
		}
		// Expiration date (Unix timestamp in seconds); skip already-expired cookies.
		var expiry int64
		if c.ExpirationDate > 0 {
			expiry = int64(c.ExpirationDate)
			if expiry < nowUnix {
				continue
			}
		} else {
			// Session cookie: default to 24h from now
			expiry = nowUnix + 24*3600
		}

		domain := strings.TrimSpace(c.Domain)
		if domain == "" || strings.ContainsAny(domain, "\r\n\t") {
			continue
		}
		// Netscape spec: if domain starts with '.', flag is TRUE (include subdomains)
		includeSubdomains := "FALSE"
		if strings.HasPrefix(domain, ".") {
			includeSubdomains = "TRUE"
		} else if !c.HostOnly {
			// If not host-only, prefix dot and set TRUE
			includeSubdomains = "TRUE"
			if !strings.HasPrefix(domain, ".") {
				domain = "." + domain
			}
		}

		path := c.Path
		if path == "" {
			path = "/"
		}

		secure := "FALSE"
		if c.Secure {
			secure = "TRUE"
		}

		// Tab-separated: domain, flag, path, secure, expiry, name, value
		line := fmt.Sprintf("%s\t%s\t%s\t%s\t%d\t%s\t%s\n",
			domain,
			includeSubdomains,
			path,
			secure,
			expiry,
			name,
			c.Value,
		)
		builder.WriteString(line)
	}

	return os.WriteFile(filePath, []byte(builder.String()), 0600)
}

// FormatCookieHeader formats a slice of cookies into a single "Cookie: k=v; k2=v2" string
// for direct HTTP requests.
func FormatCookieHeader(cookies []Cookie) string {
	if len(cookies) == 0 {
		return ""
	}
	parts := make([]string, 0, len(cookies))
	for _, c := range cookies {
		if c.Name != "" {
			parts = append(parts, fmt.Sprintf("%s=%s", c.Name, c.Value))
		}
	}
	return strings.Join(parts, "; ")
}
